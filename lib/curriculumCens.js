/**
 * Devuelve el listado completo de materias (Básicas + Orientadas) para un Año y Orientación específicos.
 */
export function getMateriasForCurso(anio, orientacion) {
  const anioNum = parseInt(anio);
  const basicaQ1 = FORMACION_BASICA[anioNum]?.Q1 || [];
  const basicaQ2 = FORMACION_BASICA[anioNum]?.Q2 || [];
  
  const orientadaObj = FORMACION_ORIENTADA[orientacion] || FORMACION_ORIENTADA['Ciencias Sociales'];
  const orientadaQ1 = orientadaObj[anioNum]?.Q1 || [];
  const orientadaQ2 = orientadaObj[anioNum]?.Q2 || [];

  const todasQ1 = Array.from(new Set([...basicaQ1, ...orientadaQ1]));
  const todasQ2 = Array.from(new Set([...basicaQ2, ...orientadaQ2]));

  return {
    Q1: todasQ1.map(nombre => ({ nombre, cuatrimestre: 'Q1' })),
    Q2: todasQ2.map(nombre => ({ nombre, cuatrimestre: 'Q2' })),
    todas: Array.from(new Set([...todasQ1, ...todasQ2])).map(nombre => ({ nombre, horas_semanales: 2 }))
  };
}
